'''Даны значения роста 20 юношей. Определить сколько юношей будут направлены 
в баскетбольную команду (рост от 190) и сколько в футбольную (остальные).'''
heights = [185, 192, 178, 190, 195, 180, 188, 193, 191, 184, 177, 196, 182, 189, 194, 176, 183, 192, 187, 190]
basketball = sum(1 for h in heights if h >= 190)
football = len(heights) - basketball
print(f"Баскетбольная команда: {basketball}")
print(f"Футбольная команда: {football}")
